// Нора — иммерсивный хаб: уровень, по которому крысы бегают между Вылазками. Всё взаимодействие — у станций.
import type { Level } from './index.js';
import { TILE } from './index.js';

export type StationId = 'stash' | 'cauldron' | 'shelf' | 'table' | 'rack' | 'tunnel';
export type Station = { id: StationId; name: string; hint: string; c0: number; c1: number; row: number };

// Легенда: # тайл, S спавн. Станции заданы отдельно (строка row — ряд, на котором стоит крыса у станции).
const GRID = [
  '################################################################',
  '################################################################',
  '####........................................................####',
  '###..........................................................###',
  '##............................................................##',
  '##............................................................##',
  '##..........................########..........................##',
  '##....................................................##......##',
  '##...........####...........................####..............##',
  '##............................................................##',
  '##............................................................##',
  '##..#####...................................######............##',
  '##.......##...............................##..................##',
  '##.SS.........................................................##',
  '################################################################',
  '################################################################',
  '################################################################',
];

export const NORA_STATIONS: Station[] = [
  { id: 'rack', name: 'Стойка Карманов', hint: 'сшить сумку — личная постройка', c0: 4, c1: 8, row: 10 },
  { id: 'cauldron', name: 'Котёл', hint: 'сварить Зелье', c0: 12, c1: 16, row: 13 },
  { id: 'stash', name: 'Склад', hint: 'куча добычи Стаи', c0: 26, c1: 38, row: 13 },
  { id: 'shelf', name: 'Полка Зелий', hint: 'выпить или взять на карту', c0: 44, c1: 49, row: 10 },
  { id: 'table', name: 'Стол с картой', hint: 'выбрать карту', c0: 52, c1: 56, row: 13 },
  { id: 'tunnel', name: 'Туннель', hint: 'в Вылазку', c0: 58, c1: 61, row: 13 },
];

export function noraLevel(): Level {
  const rows = GRID.length, cols = GRID[0].length;
  const solid = new Uint8Array(rows * cols); const spawns: { x: number; y: number }[] = [];
  for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) { const ch = GRID[r][c]; if (ch === '#') solid[r * cols + c] = 1; if (ch === 'S') spawns.push({ x: c * TILE, y: r * TILE }); }
  return { cols, rows, solid, spawns, humans: [], perches: [], items: [], exits: [], water: [], cat: null };
}

/** У какой станции стоит крыса (по AABB с запасом в полтайла). */
export function stationAt(x: number, y: number): Station | null {
  for (const s of NORA_STATIONS) {
    const sx0 = s.c0 * TILE - 8, sx1 = (s.c1 + 1) * TILE + 8, sy = s.row * TILE;
    if (x + 7 >= sx0 && x + 7 <= sx1 && Math.abs(y - sy) <= 24) return s;
  }
  return null;
}
